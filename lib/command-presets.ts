/**
 * Текст команды в том виде, в котором он попадает в поле ввода: маркеры
 * подставляются здесь, а не в тексте пресета, потому что модель не знает
 * сегодняшнего числа, а браузер знает — просить дату у юриста незачем.
 */
export function renderPresetPrompt(preset: CommandPreset, now: Date = new Date()): string {
  const today = new Intl.DateTimeFormat("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).format(now);
  return preset.prompt.split(TODAY_TOKEN).join(today);
}

/** Команды для пустого состояния чата — в том же порядке, что и в каталоге. */
export function featuredPresets(): CommandPreset[] {
  return COMMAND_PRESETS.filter((preset) => preset.featured);
}

/**
 * Поиск по названию, описанию и группе. Регистронезависимый, по подстроке:
 * юрист печатает «неуст» или «395» и ждёт расчёт неустойки.
 */
export function searchPresets(query: string): CommandPreset[] {
  const needle = query.trim().toLowerCase();
  if (!needle) {
    return COMMAND_PRESETS;
  }
  const groupTitle = new Map(COMMAND_GROUPS.map((group) => [group.id, group.title.toLowerCase()]));
  return COMMAND_PRESETS.filter((preset) => {
    const haystack = [preset.title, preset.description, groupTitle.get(preset.group) ?? ""]
      .join(" ")
      .toLowerCase();
    return haystack.includes(needle);
  });
}
