// Команды («пресеты») — готовые тексты ПОЛЬЗОВАТЕЛЬСКОГО сообщения. Клик по
// команде подставляет `prompt` в композер, юрист дозаполняет пропуски вида
// «[номер дела]» и отправляет. Системный промт при этом не участвует: для
// бэкенда это обычное сообщение, поэтому новую команду можно добавить сюда
// одной записью, ничего не трогая на сервере.
//
// Тексты держатся правил самой системы, а не общих пожеланий:
// — квадратные скобки зарезервированы под пропуски, поэтому «[ст. 333 ГК РФ]»
//   внутри промта писать нельзя: подсветится как поле для заполнения;
// — номеров страниц у модели нет, цитировать просят пункт или абзац;
// — сегодняшнюю дату модель не знает, поэтому её подставляет клиент — маркером
//   {{today}}, а не пропуском: юрист не должен вписывать то, что знает браузер;
// — требования к форме процессуального документа (реквизиты по ст. 131–132 ГПК
//   РФ, приложения, прочерки вместо неизвестных данных) уже заданы серверным
//   промтом составителя, поэтому пресеты задают только содержание;
// — поиск практики покрывает гражданские и уголовные дела СОЮ: обещать разбор
//   арбитражной практики нельзя.
